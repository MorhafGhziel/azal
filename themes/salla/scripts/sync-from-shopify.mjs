// Keeps the Salla theme in step with the Shopify theme: one AZAL design, two platforms.
//  - copies the shared scripts (azal.js, azal-home.js) into src/assets/js/azal/
//  - copies the artwork and fonts into src/assets/azal/
//  - rewrites the AZAL stylesheet so every rule only applies inside `.az` (Raed uses Tailwind, whose
//    class names such as .grid or .container would otherwise collide with AZAL's own)
// Run: node scripts/sync-from-shopify.mjs   (then pnpm run production)
import { readFileSync, writeFileSync, copyFileSync, readdirSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const shop = join(root, '..', 'shopify', 'assets');

copyFileSync(join(shop, 'azal.js'), join(root, 'src/assets/js/azal/core-impl.js'));
copyFileSync(join(shop, 'azal-home.js'), join(root, 'src/assets/js/azal/home-impl.js'));
mkdirSync(join(root, 'src/assets/azal'), { recursive: true });
let art = 0;
for (const f of readdirSync(shop)) if (/\.(webp|woff2|png)$/.test(f)) { copyFileSync(join(shop, f), join(root, 'src/assets/azal', f)); art++; }

// html-level classes the scripts set; a selector starting with one of these keeps it before `.az`
const ROOTISH = /^(:root|html|body)(\[[^\]]+\]|:[\w-]+\([^)]*\)|\.[\w-]+)*$|^\.(is-home|is-page|has-cursor|js|seen|capture|design-mode|drawer-open)(\.[\w-]+)*$/;
// rules that would restyle the whole Salla store; the Salla stylesheet sets its own versions
const DROP = new Set(['html', 'body', '*, *::before, *::after', 'img, picture, canvas, svg', 'a', 'button', ':focus-visible',
  '.is-page, .is-page body', '.view[hidden], main[hidden]', '.is-page .main']);

function scope(sel) {
  sel = sel.trim();
  if (sel.startsWith('.lenis') || sel.startsWith('html.lenis')) return sel;
  const parts = sel.split(/\s+(?![^(]*\))/);
  const first = parts[0].replace(/:has\(.*\)$/, '');
  if (ROOTISH.test(first)) {
    if (parts.length === 1) return sel; // targets <html>/<body> itself
    return [parts[0], '.az', ...parts.slice(1)].join(' ');
  }
  return `.az ${sel}`;
}

const css = readFileSync(join(shop, 'azal.css'), 'utf8') + '\n' + readFileSync(join(shop, 'azal-shop.css'), 'utf8');
const out = postcss([{
  postcssPlugin: 'azal-scope',
  Once(tree) {
    tree.walkRules((rule) => {
      if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
      if (DROP.has(rule.selector.trim())) { rule.remove(); return; }
      if (rule.selector.trim().startsWith(':root') && !/\s/.test(rule.selector.trim())) return; // token blocks
      rule.selectors = rule.selectors.map(scope);
    });
  },
}]).process(css, { from: undefined }).css
  // grain and petal images live next to the stylesheet on Salla (public/azal/)
  .replace(/var\(--img-grain\)/g, "url('azal/grain.png')")
  .replace(/var\(--img-petal-sheet\)/g, "url('azal/petal-sheet.webp')");

writeFileSync(join(root, 'src/assets/styles/azal/_ported.scss'),
  '// GENERATED by scripts/sync-from-shopify.mjs from themes/shopify/assets/azal*.css — edit those, then re-run.\n' + out);
console.log(`synced 2 scripts, ${art} artwork files, ${out.length} bytes of scoped CSS`);
