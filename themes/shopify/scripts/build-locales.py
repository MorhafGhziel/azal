def put(tree, key, val):
    parts = key.split('.')
    for p in parts[:-1]:
        tree = tree.setdefault(p, {})
    tree[parts[-1]] = val

for idx, name in ((0, 'en.default.json'), (1, 'ar.json')):
    tree = {}
    for k, v in T.items():
        put(tree, k, v[idx])
    for k, v in PLURAL.items():
        put(tree, k, v[idx])
    with open(os.path.join(root, 'locales', name), 'w', encoding='utf-8') as f:
        json.dump(tree, f, ensure_ascii=False, indent=2)
        f.write('\n')
print('wrote', len(T) + len(PLURAL), 'keys x 2 languages')
